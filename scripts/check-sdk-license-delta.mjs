import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFile, mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { toSdkStarlightPage } from './sync-local-docs.mjs';
import { FORBIDDEN_PUBLIC_DOCS_TERMS } from './public-docs-policy.mjs';
const repo = process.env.NXUSKIT_REPO;
const base = '245d7bb8217c5eacad447d3ed504601703591fcb';
const commit = '6c0412668b063c0d8da4110389cb31aa6b98dc58';
const file = 'sdk-packaging/docs/license-activation-guide.md';
const git = (...args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8' });
assert.equal(git('diff', '--name-only', base, commit, '--', 'sdk-packaging/docs').trim(), file);
const raw = git('show', `${commit}:${file}`);
const hash = value => createHash('sha256').update(value).digest('hex');
assert.equal(hash(raw), 'eaec60ef4f670939a37ef4940358e967f144dbac2dadeb010e57d6f9dc853b9b');
const changelog = git('show', `${commit}:CHANGELOG.md`);
const page = toSdkStarlightPage(raw, 'license-activation-guide.md', changelog);
const old = await readFile('tmp/ga-d01-draft-Hzms2R/concepts/licensing.md', 'utf8');
const split = text => text.split('#### Real-purchase activation (production)');
assert.equal(split(page)[0], split(old)[0]);
assert.equal(split(page)[1].split('```bash')[1], split(old)[1].split('```bash')[1]);
assert.match(page, /Actual availability[\s\S]*verified[\s\S]*Website W02 \/ Licensing L01 service/);
assert.doesNotMatch(page, /Each card shows the/);
assert.match(page, /https:\/\/nxus.systems\/shop/);
assert.match(page, /https:\/\/nxus.systems\/my\/products/);
assert.match(page, /--key "\$NXUSKIT_PURCHASE_ID" --accept-eula --json/);
assert.equal(page.match(/^description:.*$/m)[0], old.match(/^description:.*$/m)[0]);
assert.deepEqual([...page.matchAll(/\]\(([^)]+)\)/g)].map(m=>m[1]), [...old.matchAll(/\]\(([^)]+)\)/g)].map(m=>m[1]));
for (const term of FORBIDDEN_PUBLIC_DOCS_TERMS) assert.ok(!page.includes(term), term);
assert.ok(!/\/Users\/|\/home\/|[a-f0-9]{40}|codex\/|TODO|TBD/.test(page));
await mkdir('tmp', { recursive: true });
const output = await mkdtemp('tmp/ga-d01-license-delta-');
await writeFile(`${output}/licensing.md`, page);
console.log(JSON.stringify({ commit, sourceSha256: hash(raw), output, pageSha256: hash(page), result: 'PASS sole-guide delta, source hash, conditionality, unchanged metadata/links/command/rest-of-body, strict leaks; no HTML render' }));
